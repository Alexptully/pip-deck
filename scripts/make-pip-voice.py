"""
Records every line Pip says out loud with Kokoro, an open neural voice model that runs offline,
and writes the clips into src/content/pip-voice-clips.ts so the deck plays real recordings
instead of the browser's text to speech.

Run it again whenever a spoken line in pipCues changes:

    pip install kokoro-onnx soundfile
    python3 scripts/make-pip-voice.py

It needs ffmpeg with the rubberband filter. The model files (about 350 MB) download once
into ~/.cache/pip-voice.
"""

import base64
import json
import subprocess
import tempfile
import urllib.request
from pathlib import Path

import soundfile
from kokoro_onnx import Kokoro

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "content" / "pip-voice-clips.ts"
CACHE = Path.home() / ".cache" / "pip-voice"
RELEASE = "https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0"
MODEL_FILES = ["kokoro-v1.0.onnx", "voices-v1.0.bin"]

# Pip's voice: mostly af_heart (warm and natural) with some af_bella (brighter), spoken a
# little quicker than normal. The pitch then goes up about a semitone and a half, with the
# formants moving too, so Pip sounds small and friendly without sounding sped up.
VOICE_MIX = {"af_heart": 0.7, "af_bella": 0.3}
SPEED = 1.06
PITCH = 1.09


def download_models() -> None:
    CACHE.mkdir(parents=True, exist_ok=True)
    for name in MODEL_FILES:
        target = CACHE / name
        if not target.exists():
            print(f"Downloading {name}")
            urllib.request.urlretrieve(f"{RELEASE}/{name}", target)


def spoken_lines() -> list[str]:
    result = subprocess.run(
        ["node", "scripts/pip-voice-lines.mjs"], cwd=ROOT, check=True, capture_output=True, text=True
    )
    return json.loads(result.stdout)


def blended_voice(kokoro: Kokoro):
    return sum(kokoro.get_voice_style(name) * weight for name, weight in VOICE_MIX.items())


def polish(raw: Path, finished: Path) -> None:
    """Raises the pitch, trims silence, evens out loudness and encodes a small mp3."""
    filters = ",".join(
        [
            f"rubberband=pitch={PITCH}:formant=shifted",
            "silenceremove=start_periods=1:start_threshold=-45dB",
            "areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse",
            "highpass=f=90",
            "loudnorm=I=-16:TP=-1.5",
            "afade=t=in:d=0.02",
        ]
    )
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-i", str(raw), "-af", filters,
         "-ar", "24000", "-ac", "1", "-b:a", "64k", str(finished)],
        check=True,
    )


def record(kokoro: Kokoro, style, line: str, folder: Path, index: int) -> str:
    samples, rate = kokoro.create(line, voice=style, speed=SPEED, lang="en-us")
    raw = folder / f"{index}.wav"
    finished = folder / f"{index}.mp3"
    soundfile.write(raw, samples, rate)
    polish(raw, finished)
    return "data:audio/mpeg;base64," + base64.b64encode(finished.read_bytes()).decode()


def write_module(clips: dict[str, str]) -> None:
    entries = "\n".join(f"  {json.dumps(line)}:\n    {json.dumps(uri)}," for line, uri in clips.items())
    OUTPUT.write_text(
        "// Generated by scripts/make-pip-voice.py. Run it again after changing a spoken line.\n"
        "// Each entry maps a line Pip says out loud to a recording of it.\n\n"
        f"export const pipVoiceClips: Record<string, string> = {{\n{entries}\n}};\n"
    )


def main() -> None:
    download_models()
    kokoro = Kokoro(str(CACHE / MODEL_FILES[0]), str(CACHE / MODEL_FILES[1]))
    style = blended_voice(kokoro)
    lines = spoken_lines()
    with tempfile.TemporaryDirectory() as folder:
        clips = {line: record(kokoro, style, line, Path(folder), index) for index, line in enumerate(lines)}
    write_module(clips)
    print(f"Recorded {len(clips)} lines into {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
